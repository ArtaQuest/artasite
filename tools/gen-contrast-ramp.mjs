#!/usr/bin/env node
/**
 * ArtaContrast — pre-paint CSS ramp generator.
 *
 * The [data-contrast] ramp in artaquest-web/src/index.css must be EXACTLY what the runtime engine
 * (lib/contrast.ts applyContrast) would set, or pages repaint/jump after hydration. This script is
 * the only way the ramp is written: it bundles the engine with esbuild, calls the SAME tokensFor()
 * the runtime uses — 5 levels × 2 themes on each theme's default --color-space-2 canvas — and
 * rewrites the block between the AQ_CONTRAST_RAMP markers in index.css.
 *
 *   node tools/gen-contrast-ramp.mjs          # regenerate (writes index.css when it changed)
 *   node tools/gen-contrast-ramp.mjs --check  # exit 1 if index.css is stale (CI / pre-deploy gate)
 */
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const WEB = join(ROOT, "artaquest-web");
const CSS = join(WEB, "src", "index.css");

// Bundle the engine (TypeScript) with the project's own bundler (rolldown — vite 8's core) so this
// script needs no extra deps.
const { rolldown } = await import(pathToFileURL(join(WEB, "node_modules", "rolldown", "dist", "index.mjs")));
const tmp = mkdtempSync(join(tmpdir(), "aq-ramp-"));
const out = join(tmp, "contrast.mjs");
const bundle = await rolldown({ input: join(WEB, "src", "lib", "contrast.ts") });
await bundle.write({ file: out, format: "esm" });
await bundle.close();
const engine = await import(pathToFileURL(out));
rmSync(tmp, { recursive: true, force: true });

// The default canvases the pre-paint ramp is solved against: each theme's --color-space-2 (cards; the
// text canvas) and --color-space-1 (the page; hairlines paint on both, so the line token solves on both).
// The runtime refines against the LIVE canvases; on the default themes these are identical.
const css = readFileSync(CSS, "utf8");
const spaceOf = (block, n) => {
  const m = block.match(new RegExp(`--color-space-${n}:\\s*(#[0-9a-fA-F]{6})`));
  if (!m) throw new Error(`could not read --color-space-${n} from index.css`);
  return engine.parseHex(m[1]);
};
const lightBlock = css.match(/html\[data-theme="light"\][^{]*\{[\s\S]*?\n\}/)?.[0] ?? "";
const CANVAS = { dark: spaceOf(css, 2), light: spaceOf(lightBlock, 2) };
const CANVAS1 = { dark: spaceOf(css, 1), light: spaceOf(lightBlock, 1) };

const line = (sel, tokens) => `${sel}{${Object.entries(tokens).map(([k, v]) => `${k}:${v}`).join(";")}}`;
const lines = [];
for (const theme of ["dark", "light"]) {
  for (let lv = 1; lv <= engine.LEVELS; lv++) {
    const sel = theme === "dark" ? `html[data-contrast="${lv}"]` : `html[data-theme="light"][data-contrast="${lv}"]`;
    lines.push(line(sel, engine.tokensFor(lv, theme, CANVAS[theme], CANVAS1[theme])));
  }
}
const START = "/* AQ_CONTRAST_RAMP_START — generated by tools/gen-contrast-ramp.mjs; do not hand-edit */";
const END = "/* AQ_CONTRAST_RAMP_END */";
const block = `${START}\n${lines.join("\n")}\n${END}`;

const re = new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`);
if (!re.test(css)) {
  console.error("AQ_CONTRAST_RAMP markers not found in index.css — add them around the ramp block first.");
  process.exit(2);
}
const next = css.replace(re, block);
if (next === css) {
  console.log("ramp up to date");
  process.exit(0);
}
if (process.argv.includes("--check")) {
  console.error("index.css contrast ramp is STALE — run: node tools/gen-contrast-ramp.mjs");
  process.exit(1);
}
writeFileSync(CSS, next);
console.log("index.css contrast ramp regenerated");
